import Foundation

@MainActor
/// Предоставляет независимый от способа хранения доступ к истории расчётов пользователя.
protocol HistoryRepository {

    /// Определяет, доступна ли пользователю история расчётов в текущей реализации.
    ///
    /// Значение используется для показа навигации к истории, но не отменяет обработку ошибок операций репозитория.
    var isHistoryAvailable: Bool { get }

    /// Загружает все сохранённые расчёты в порядке от новых к старым.
    ///
    /// - Returns: Сохранённые исходные параметры расчётов.
    /// - Throws: Ошибку чтения хранилища.
    func loadAll() throws -> [HistoryEntry]

    /// Сохраняет исходные параметры, если в локальный день ещё нет эквивалентной записи.
    ///
    /// - Parameters:
    ///   - input: Исходные значения, введённые пользователем.
    ///   - date: Дата и время выполнения расчёта.
    /// - Throws: Ошибку чтения или записи хранилища.
    func saveIfNeeded(_ input: CalculationInput, at date: Date) throws

    /// Удаляет одну запись истории.
    ///
    /// - Parameter id: Идентификатор удаляемой записи.
    /// - Throws: Ошибку чтения или записи хранилища.
    func delete(id: UUID) throws

    /// Удаляет все записи истории.
    ///
    /// - Throws: Ошибку записи хранилища.
    func deleteAll() throws
}
